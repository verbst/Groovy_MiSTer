// slate.h — dependency-free text "slate" renderer shared by the test sender (marker_sender.cpp) and the
// frame generator (nlc_synth.cpp). Draws a self-identifying settings card (resolution / codec / rgb / fps)
// into a framebuffer in the SAME FB byte order the FPGA scans out, so the slate is pixel-identical on
// hardware and in the sim.
//
// Font: the MiSTer OSD 8x8 charset (defchars) lifted verbatim from hps_linux/src/user_io.cpp — 64 glyphs,
// 8 rows each, bit7 = leftmost column. Index map (verified against the table): ' '=0, '0'..'9'=28..37,
// 'A'..'Z'=38..63, plus a few punctuation glyphs.
//
// FB byte order: RGB888 (bpp=3) = B,G,R per pixel (matches Groovy.sv decode_pixel default + nlc_synth raw).
//                RGB565 (bpp=2) = little-endian R5G6B5 (exercised in the later RGB565 phase; verify on HW).
