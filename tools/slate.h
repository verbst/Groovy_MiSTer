// ASCII -> glyph index (uppercase only; unknown -> space). Lowercase folded to uppercase.
static inline int slate_glyph(char c)
{
	if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
	if (c == ' ') return 0;
	if (c >= '0' && c <= '9') return 28 + (c - '0');
	if (c >= 'A' && c <= 'Z') return 38 + (c - 'A');
	switch (c) {
		case '.': return 27;
		case ',': return 26;
		case '/': return 24;
		case '-': return 22;
		case '+': return 21;
		case '=': return 20;
		case '(': return 16;
		case ')': return 17;
		case '?': return 15;
		default:  return 0;
	}
}

static inline void slate_put(uint8_t* fb, int W, int bpp, int x, int y,
                             uint8_t r, uint8_t g, uint8_t b)
{
	size_t i = ((size_t)y * W + x) * bpp;
	if (bpp == 3) { fb[i] = b; fb[i + 1] = g; fb[i + 2] = r; }          // FB order B,G,R
	else          { uint16_t v = (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
	                fb[i] = (uint8_t)(v & 0xFF); fb[i + 1] = (uint8_t)(v >> 8); }  // LE RGB565
}

static inline void slate_fill(uint8_t* fb, int W, int H, int bpp,
                              uint8_t r, uint8_t g, uint8_t b)
{
	for (int y = 0; y < H; y++) for (int x = 0; x < W; x++) slate_put(fb, W, bpp, x, y, r, g, b);
}

// draw one char at (px,py) with integer scale; each set font bit -> scale*scale block.
static inline void slate_char(uint8_t* fb, int W, int H, int bpp, int px, int py, int scale,
                              char c, uint8_t r, uint8_t g, uint8_t b)
{
	const unsigned char* gl = &slate_defchars[slate_glyph(c) * 8];
	for (int row = 0; row < 8; row++) {
		unsigned char bits = gl[row];
		for (int col = 0; col < 8; col++) {
			if (!((bits >> (7 - col)) & 1)) continue;
			for (int dy = 0; dy < scale; dy++) for (int dx = 0; dx < scale; dx++) {
				int x = px + col * scale + dx, y = py + row * scale + dy;
				if (x >= 0 && x < W && y >= 0 && y < H) slate_put(fb, W, bpp, x, y, r, g, b);
			}
		}
	}
}

// draw a string left-to-right; advance 8*scale per glyph cell (bit0 unused -> 1-col gap).
static inline void slate_text(uint8_t* fb, int W, int H, int bpp, int px, int py, int scale,
                              const char* s, uint8_t r, uint8_t g, uint8_t b)
{
	for (int i = 0; s[i]; i++)
		slate_char(fb, W, H, bpp, px + i * 8 * scale, py, scale, s[i], r, g, b);
}

// Compose a full slate: dark background + each line in high-contrast white, top-aligned, centered-ish.
// lines[] is caller-built from the actual run params; nlines lines, integer scale (default caller picks 3).
static inline void slate_compose(uint8_t* fb, int W, int H, int bpp,
                                 const char* const* lines, int nlines, int scale)
{
	slate_fill(fb, W, H, bpp, 0, 0, 32);                     // very dark blue background
	int gh = 8 * scale, gap = scale, lh = gh + gap;
	int total = nlines * lh - gap;
	int y0 = (H - total) / 2; if (y0 < scale) y0 = scale;
	for (int i = 0; i < nlines; i++) {
		const char* s = lines[i];
		int len = (int)strlen(s);
		int tw = len * 8 * scale;
		int x0 = (W - tw) / 2; if (x0 < scale) x0 = scale;
		slate_text(fb, W, H, bpp, x0, y0 + i * lh, scale, s, 255, 255, 255);
	}
}

// Build the canonical slate lines from the actual run parameters, so the sender (hardware) and nlc_synth
// (sim) produce BYTE-identical text. Caller supplies storage `buf[6][24]`; returns the line count and points
// lines[] at buf rows. Keep every line <= 13 chars so it fits 320px at scale 3. take<0 omits the TAKE line.
static inline int slate_build(char buf[6][24], const char* lines[6],
                              int W, int H, int interlace, int depth,
                              const char* codec, int fps, double clkMHz, int take)
{
	int n = 0;
	snprintf(buf[n], 24, "GROOVY TEST");                                   lines[n] = buf[n]; n++;
	snprintf(buf[n], 24, "RES %dX%d%c", W, H, interlace ? 'I' : 'P');      lines[n] = buf[n]; n++;
	snprintf(buf[n], 24, "CODEC %s", codec);                              lines[n] = buf[n]; n++;
	snprintf(buf[n], 24, "RGB%s %dFPS", (depth == 2) ? "565" : "888", fps); lines[n] = buf[n]; n++;
	snprintf(buf[n], 24, "CLK %.2fMHZ", clkMHz);                          lines[n] = buf[n]; n++;
	if (take >= 0) { snprintf(buf[n], 24, "TAKE %03d", take);             lines[n] = buf[n]; n++; }
	return n;
}

